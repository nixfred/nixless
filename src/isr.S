# Exception entry stubs. Each stub normalizes the stack to
#   [vector][error code][rip][cs][rflags][rsp][ss]
# (pushing a zero error code where the CPU pushes none), then jumps to the
# common path, which saves all GPRs and calls exception_dispatch(frame).
# Intel SDM Vol. 3 section 6.15 (which vectors push an error code).

.section .text

.macro isr_noerr n
.global isr_\n
isr_\n:
    pushq $0
    pushq $\n
    jmp isr_common
.endm

.macro isr_err n
.global isr_\n
isr_\n:
    pushq $\n
    jmp isr_common
.endm

